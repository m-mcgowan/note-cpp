#pragma once

/// @file generic_sink.hpp
/// GenericResponseSink — table-driven SAX sink for response parsing.
///
/// A single, non-template sink type that dispatches SAX events to struct
/// fields using a compile-time field descriptor table. Because it's one
/// concrete type, make_sax_dispatch<GenericResponseSink> generates exactly
/// ONE set of dispatch thunks shared by all response types — eliminating
/// the per-endpoint thunk duplication that dominates flash on AVR.
///
/// Each response type generates a static `fields[]` array (data, not code)
/// describing its field names, offsets, and types. At runtime, on_bool/
/// on_int/on_float/on_string iterate the table to find the matching field.
///
/// Trade-off: O(N) key lookup per event instead of compiler-generated
/// if-chains. For typical Notecard responses (<10 fields), this is a few
/// extra string comparisons — negligible vs. the transport I/O.

#include <note/json_sax.hpp>
#include <note/string_pool.hpp>
#include <note/types.hpp>

#include <cstdint>

namespace note {

/// Field type discriminator — matches the SAX event that delivers the value.
enum class FieldType : uint8_t {
    Bool,
    Int32,
    Double,    // stored as double (ResponseField<double>)
    String,    // interned via StringPool, stored as string_view
};

/// Describes one response field: its JSON key, byte offset in the response
/// struct, and value type. Generated by codegen as a static const array.
struct FieldDesc {
    const char* name;     // JSON key name
    uint16_t offset;      // byte offset of value_ within the response struct
    FieldType type;       // value type
};

/// Non-template sink — one instantiation for all response types.
struct GenericResponseSink {
    void* rsp;              // pointer to response struct
    const FieldDesc* fields;
    uint8_t n_fields;
    StringPool* pool;

    void on_null(string_view) {}

    void on_bool(string_view k, bool v) {
        for (uint8_t i = 0; i < n_fields; ++i) {
            if (fields[i].type == FieldType::Bool && k == fields[i].name) {
                *field_ptr<bool>(i) = v;
                return;
            }
        }
    }

    void on_int(string_view k, int32_t v) {
        for (uint8_t i = 0; i < n_fields; ++i) {
            if (fields[i].type == FieldType::Int32 && k == fields[i].name) {
                *field_ptr<int32_t>(i) = v;
                return;
            }
        }
    }

    void on_float(string_view k, double v) {
        for (uint8_t i = 0; i < n_fields; ++i) {
            if (fields[i].type == FieldType::Double && k == fields[i].name) {
                *field_ptr<double>(i) = v;
                return;
            }
        }
    }

    void on_string(string_view k, string_view v) {
        for (uint8_t i = 0; i < n_fields; ++i) {
            if (fields[i].type == FieldType::String && k == fields[i].name) {
                *field_ptr<string_view>(i) = pool->intern(v);
                return;
            }
        }
    }

    void on_number(string_view, string_view) {}
    void on_object_begin(string_view) {}
    void on_object_end(string_view) {}
    void on_array_begin(string_view) {}
    void on_array_end(string_view) {}

    void reset() {
        for (uint8_t i = 0; i < n_fields; ++i) {
            switch (fields[i].type) {
            case FieldType::Bool:   *field_ptr<bool>(i) = false; break;
            case FieldType::Int32:  *field_ptr<int32_t>(i) = 0; break;
            case FieldType::Double: *field_ptr<double>(i) = 0.0; break;
            case FieldType::String: *field_ptr<string_view>(i) = {}; break;
            }
        }
    }

private:
    template<typename T>
    T* field_ptr(uint8_t i) {
        return reinterpret_cast<T*>(static_cast<char*>(rsp) + fields[i].offset);
    }
};

} // namespace note
